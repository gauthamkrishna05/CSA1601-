dir.create("plots", showWarnings = FALSE)
set.seed(123)
x <- rnorm(200, mean = 50, sd = 10)
png("plots/16_histogram.png", width = 800, height = 600)
hist(x, main = "Histogram of Random Data", xlab = "Values", ylab = "Frequency", col = "orange", border = "black")
dev.off()
cat("Histogram saved to plots/16_histogram.png\n")
cat("Sample mean =", mean(x), "\n")
cat("Sample standard deviation =", sd(x), "\n")
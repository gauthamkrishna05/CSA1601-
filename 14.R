dir.create("plots", showWarnings = FALSE)
subjects <- c("Maths", "Science", "English", "Computer", "Social")
marks <- c(85, 78, 92, 88, 75)
print(data.frame(Subject = subjects, Marks = marks))
png("plots/14_bar_vertical.png", width = 800, height = 600)
barplot(marks, names.arg = subjects, main = "Vertical Bar Plot - Marks by Subject", xlab = "Subjects", ylab = "Marks", col = "skyblue")
dev.off()
png("plots/14_bar_horizontal.png", width = 800, height = 600)
barplot(marks, names.arg = subjects, main = "Horizontal Bar Plot - Marks by Subject", xlab = "Marks", ylab = "Subjects", col = "lightgreen", horiz = TRUE)
dev.off()
cat("Bar plots saved to plots/14_bar_vertical.png and plots/14_bar_horizontal.png\n")
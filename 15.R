dir.create("plots", showWarnings = FALSE)
g1 <- c(12, 15, 18, 20, 25, 30)
g2 <- c(10, 14, 17, 22, 28, 35)
g3 <- c(8, 12, 16, 19, 24, 29)
png("plots/15_boxplot.png", width = 800, height = 600)
boxplot(g1, g2, g3, names = c("Group A", "Group B", "Group C"), main = "Box Plot of Three Groups", xlab = "Groups", ylab = "Values", col = c("lightblue", "lightgreen", "lightpink"))
dev.off()
cat("Box plot saved to plots/15_boxplot.png\n")
cat("Group A summary:\n")
print(summary(g1))